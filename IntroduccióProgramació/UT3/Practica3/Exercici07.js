// == indica que els dos valors són iguals però és indiferent si és un nombre on un string.
// === Indica que els dos nombres són iguals i els dos són nombres.

console.log( 5 == "5" ); // true
console.log( 5 === "5" ); // false
console.log( 0 == false ); // true
console.log( 0 === false ); // false
